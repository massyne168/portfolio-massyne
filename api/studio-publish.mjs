import { isStudioSessionAuthenticated } from "./studio-access.mjs";

const REPOSITORY = "massyne168/portfolio-massyne";
const GITHUB_API = "https://api.github.com";
const MAX_CONTENT_BYTES = 1_000_000;
const DEFAULT_SITE_COLORS = Object.freeze({ accent: "#990011", light: "#FCF6F5" });

function safeColor(value, fallback) {
  const color = typeof value === "string" ? value.trim() : "";
  return /^#[0-9a-f]{6}$/i.test(color) ? color.toUpperCase() : fallback;
}

function normalizedContent(content) {
  const sourceColors = content.site.colors && typeof content.site.colors === "object" && !Array.isArray(content.site.colors)
    ? content.site.colors
    : {};
  return {
    ...content,
    site: {
      ...content.site,
      colors: {
        accent: safeColor(sourceColors.accent, DEFAULT_SITE_COLORS.accent),
        light: safeColor(sourceColors.light, DEFAULT_SITE_COLORS.light)
      }
    }
  };
}

function paletteStyles(colors) {
  return `/* Generated by MASSYNE Studio from site appearance settings. */
:root {
  --site-accent: ${safeColor(colors.accent, DEFAULT_SITE_COLORS.accent)};
  --site-light: ${safeColor(colors.light, DEFAULT_SITE_COLORS.light)};
}
:root[data-theme="light"] {
  --ink: var(--site-light);
  --ink-soft: color-mix(in srgb, var(--site-light) 92%, var(--site-accent));
  --surface: color-mix(in srgb, var(--site-light) 90%, var(--site-accent));
  --paper: var(--site-accent);
  --muted: color-mix(in srgb, var(--site-accent) 64%, var(--site-light));
  --red: var(--site-accent);
  --red-bright: var(--site-accent);
  --line: color-mix(in srgb, var(--site-accent) 16%, transparent);
  --ui-stroke: color-mix(in srgb, var(--site-accent) 35%, transparent);
  --ui-focus: var(--site-accent);
  --theme-surface: var(--site-light);
  --theme-text: var(--site-accent);
  --theme-border: color-mix(in srgb, var(--site-accent) 18%, transparent);
}
:root[data-theme="dark"] {
  --paper: var(--site-light);
  --red: var(--site-accent);
  --red-bright: var(--site-accent);
  --theme-text: var(--site-light);
  --theme-border: color-mix(in srgb, var(--site-light) 18%, transparent);
  --ui-focus: var(--site-light);
}
`;
}

function send(res, status, body) {
  return res.status(status).json(body);
}

function readBody(req) {
  if (req.body && typeof req.body === "object") return req.body;
  if (typeof req.body === "string") {
    try { return JSON.parse(req.body); } catch (_) { return {}; }
  }
  return {};
}

function originAllowed(req) {
  const headers = req.headers || {};
  const origin = String(headers.origin || "");
  const host = String(headers.host || "");
  if (!origin || !host) return true;
  try {
    return new URL(origin).host.toLowerCase() === host.toLowerCase();
  } catch (_) {
    return false;
  }
}

function buildFiles(source) {
  const content = normalizedContent(source);
  const contentJson = JSON.stringify(content, null, 2) + "\n";
  const projectSource = "/* MASSYNE — individual original artwork captions and grounded concept notes. */\n"
    + "window.MASSYNE_PROJECTS = " + JSON.stringify(content.projects, null, 2) + ";\n";
  const contentScript = "/* Generated by MASSYNE STUDIO from studio-content.json. */\n"
    + "window.MASSYNE_STUDIO_CONTENT = " + JSON.stringify(content, null, 2) + ";\n";
  return [
    { path: "studio-content.json", content: contentJson },
    { path: "project-data.js", content: projectSource },
    { path: "studio-content.js", content: contentScript },
    { path: "site-theme.css", content: paletteStyles(content.site.colors) }
  ];
}

async function githubRequest(token, path, options = {}) {
  const response = await fetch(GITHUB_API + path, {
    ...options,
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: "Bearer " + token,
      "X-GitHub-Api-Version": "2022-11-28",
      "Content-Type": "application/json",
      ...(options.headers || {})
    }
  });
  const body = await response.json().catch(() => ({}));
  if (!response.ok) {
    const error = new Error(body.message || "GitHub returned " + response.status + ".");
    error.status = response.status;
    throw error;
  }
  return body;
}

async function connectionStatus(res, token) {
  if (!token) {
    return send(res, 200, {
      connected: false,
      message: "Add the fine-grained GitHub token to the Vercel Production environment, then redeploy."
    });
  }
  try {
    const repository = await githubRequest(token, "/repos/" + REPOSITORY);
    const connected = String(repository.full_name || "").toLowerCase() === REPOSITORY;
    return send(res, 200, {
      connected,
      message: connected
        ? "GitHub publishing is connected securely through Vercel."
        : "The Vercel token needs access to this repository with Contents: Read and write."
    });
  } catch (error) {
    if ([401, 403, 404].includes(error.status)) {
      return send(res, 200, {
        connected: false,
        message: "The Vercel GitHub token is invalid or lacks access to this repository."
      });
    }
    return send(res, 502, {
      connected: false,
      message: "GitHub could not be checked right now. Try again."
    });
  }
}

function validateContent(content) {
  if (!content || typeof content !== "object" || Array.isArray(content)) return false;
  if (!content.site || typeof content.site !== "object" || Array.isArray(content.site)) return false;
  return ["projects", "archive", "motion", "services"].every(key => Array.isArray(content[key]));
}

async function createCommit(token, files) {
  const ref = await githubRequest(token, "/repos/" + REPOSITORY + "/git/ref/heads/main");
  const parent = ref.object?.sha;
  if (!parent) throw new Error("GitHub could not read the main branch.");
  const current = await githubRequest(token, "/repos/" + REPOSITORY + "/git/commits/" + parent);
  const blobs = await Promise.all(files.map(async file => {
    const blob = await githubRequest(token, "/repos/" + REPOSITORY + "/git/blobs", {
      method: "POST",
      body: JSON.stringify({ content: file.content, encoding: "utf-8" })
    });
    return { path: file.path, mode: "100644", type: "blob", sha: blob.sha };
  }));
  const tree = await githubRequest(token, "/repos/" + REPOSITORY + "/git/trees", {
    method: "POST",
    body: JSON.stringify({ base_tree: current.tree.sha, tree: blobs })
  });
  const commit = await githubRequest(token, "/repos/" + REPOSITORY + "/git/commits", {
    method: "POST",
    body: JSON.stringify({
      message: "Update portfolio content from MASSYNE Studio",
      tree: tree.sha,
      parents: [parent]
    })
  });
  await githubRequest(token, "/repos/" + REPOSITORY + "/git/refs/heads/main", {
    method: "PATCH",
    body: JSON.stringify({ sha: commit.sha, force: false })
  });
  return commit.sha;
}

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store, max-age=0");
  res.setHeader("Pragma", "no-cache");
  res.setHeader("X-Content-Type-Options", "nosniff");

  if (req.method !== "GET" && req.method !== "POST") {
    res.setHeader("Allow", "GET, POST");
    return send(res, 405, { message: "Method not allowed." });
  }
  if (!isStudioSessionAuthenticated(req)) {
    return send(res, 401, { connected: false, message: "Open MASSYNE Studio again to continue." });
  }
  if (!originAllowed(req)) {
    return send(res, 403, { message: "Access denied." });
  }

  const token = String(process.env.MASSYNE_STUDIO_GITHUB_TOKEN || "").trim();
  if (req.method === "GET") return connectionStatus(res, token);
  if (!token) {
    return send(res, 503, { message: "GitHub publishing is not configured in Vercel yet." });
  }

  const body = readBody(req);
  const content = body.content;
  if (!validateContent(content)) {
    return send(res, 400, { message: "The Studio content package is incomplete." });
  }
  const contentBytes = Buffer.byteLength(JSON.stringify(content), "utf8");
  if (contentBytes > MAX_CONTENT_BYTES) {
    return send(res, 413, { message: "The content package is too large to publish." });
  }

  try {
    const commit = await createCommit(token, buildFiles(content));
    return send(res, 200, { ok: true, commit });
  } catch (error) {
    if (error.status === 409 || error.status === 422) {
      return send(res, 409, { message: "The main branch changed while saving. Refresh Studio and try again." });
    }
    if ([401, 403].includes(error.status)) {
      return send(res, 503, { message: "The Vercel GitHub token needs repository Contents: Read and write access." });
    }
    return send(res, 502, { message: "GitHub could not save these changes. Try again." });
  }
}
